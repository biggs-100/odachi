package persona

import "strings"

// RoleFile composes the agent file of one role for one client: the client's own
// frontmatter, the same block odachi reads, and the role section. The description
// is the role's trigger, because that is what the client lists.
func RoleFile(client, slug, description, block, section string) (File, bool) {
	key := strings.ToLower(strings.TrimSpace(client))
	for _, row := range clients {
		if row.Agent != key {
			continue
		}
		wrapper := roleWrapper(row.Agent, slug, description)
		if wrapper == "" {
			return File{}, false
		}
		seal := "The role of this agent is the one in .odachi/roles/" + slug + ".md; the rules are the project's block. Do not edit it by hand: odachi role " + slug + " rewrites it."
		return File{
			Path:    row.Dir + "/" + slug + ".md",
			Content: wrapper + roleGenerated(slug) + "\n" + seal + "\n\n" + block + "\n\n" + section,
		}, true
	}
	return File{}, false
}

// roleWrapper is the frontmatter one client needs for a role. It differs from
// the odachi agent's wrapper in one thing: the name and the description are the
// role's, because the selector lists what the frontmatter says.
func roleWrapper(agent, slug, description string) string {
	switch agent {
	case "opencode":
		return "---\ndescription: \"" + description + "\"\nmode: primary\n---\n"
	case "claude":
		return "---\nname: " + slug + "\ndescription: \"" + description + "\"\nkeep-coding-instructions: true\n---\n"
	}
	return ""
}

// roleGenerated is the note a rendered role carries. It names the command that
// rewrites it: the init note would send a human to a command that does not
// write this file.
func roleGenerated(slug string) string {
	return "<!-- generated by odachi role " + slug + "; do not edit by hand: it is rewritten every time you run odachi role " + slug + " -->"
}
