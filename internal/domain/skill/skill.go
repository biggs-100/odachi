// Package skill owns the skills format: the frontmatter every SKILL.md declares,
// the rules that make a skill loadable, and the generated SKILLS.md registry.
//
// It is pure: no filesystem, no os. The app layer reads the files over its port
// and hands the bytes here, so `--check` gives the same answer on every machine.
package skill

import (
	"fmt"
	"regexp"
	"slices"
	"sort"
	"strings"
	"unicode/utf8"
)

// RegistryHeader is the first line of the generated registry. It says who owns
// the file: --write, never a human.
const RegistryHeader = "<!-- generated by odachi skills --write; do not edit it by hand -->"

// RegistryFile is the generated index of every skill, at the project root.
const RegistryFile = "SKILLS.md"

// The limits Contract VII fixes. They are exported so the message a human reads
// and the rule that refuses the file can never disagree.
const (
	// MaxDescription is the most characters a description may have.
	MaxDescription = 200
	// MaxBodyLines is the most lines a skill body may have.
	MaxBodyLines = 60
	// TriggerPrefix is how every description starts.
	TriggerPrefix = "Trigger:"
	// NamePattern is the one slug shape a directory and a name share.
	NamePattern = `^[a-z][a-z0-9-]{2,40}$`
)

// requiredSections are the three headings every skill body carries, in order.
var requiredSections = []string{"When", "Rules", "Never"}

var namePattern = regexp.MustCompile(NamePattern)

// Skill is one parsed SKILL.md. Dir is its directory name, which the declared
// name has to match; Path is how the file is named in messages and the registry.
type Skill struct {
	Dir         string
	Path        string
	Name        string
	Description string
	Trigger     string
	Body        string
	// Raw is the exact bytes this file was parsed from: pack installs them, and
	// a copy that re-renders a skill would not be the skill.
	Raw            []byte
	HasFrontmatter bool
	// References is what the skill folder holds under references/, as paths
	// relative to the folder ("references/numbers.md"), sorted. The loader reads
	// the disk; Parse cannot, so a skill parsed alone carries none and the
	// reference rules have nothing to contradict.
	References []string
	// FolderProblems are the violations the loader found while reading the
	// folder, such as a references entry that is not a file. They belong to the
	// skill even though they are not in its text.
	FolderProblems []Problem
}

// Problem is one violation, attributed to the file a human has to open.
type Problem struct {
	File   string
	Reason string
}

// Parse reads one SKILL.md. It is total: malformed input never panics, it just
// fails validation later.
func Parse(dir, path, text string) Skill {
	s := Skill{Dir: dir, Path: path, Body: text, Raw: []byte(text)}

	front, body, ok := splitFrontmatter(text)
	if !ok {
		return s
	}

	s.HasFrontmatter = true
	s.Body = body
	s.Name = frontmatterValue(front, "name")
	s.Description = frontmatterValue(front, "description")
	s.Trigger = strings.TrimSpace(strings.TrimPrefix(s.Description, TriggerPrefix))
	return s
}

// Problems reports every violation in this file, one reason each.
func (s Skill) Problems() []Problem {
	problems := []Problem{}
	add := func(format string, args ...any) {
		problems = append(problems, Problem{File: s.Path, Reason: fmt.Sprintf(format, args...)})
	}

	if !s.HasFrontmatter {
		return []Problem{{File: s.Path, Reason: "there is no frontmatter: the file must start with --- and close it with ---"}}
	}

	if s.Name == "" {
		add("the frontmatter does not say name")
	} else {
		if !namePattern.MatchString(s.Name) {
			add("the name %q does not match the shape %s (lowercase letters, numbers and dashes, starting with a letter)", s.Name, NamePattern)
		}
		if s.Name != s.Dir {
			add("the name %q does not match the directory %q", s.Name, s.Dir)
		}
	}

	if s.Description == "" {
		add("the frontmatter does not say description")
	} else {
		if !strings.HasPrefix(s.Description, TriggerPrefix) {
			add("the description does not start with %q: nobody knows when to load the skill", TriggerPrefix)
		}
		if length := utf8.RuneCountInString(s.Description); length > MaxDescription {
			add("the description has %d characters; the maximum is %d", length, MaxDescription)
		}
	}

	body := bodyLines(s.Body)
	if len(body) > MaxBodyLines {
		add("the body has %d lines; the maximum is %d", len(body), MaxBodyLines)
	}
	if strings.Contains(s.Body, "TODO") {
		add("the body contains TODO: a skill ships complete or it does not ship")
	}

	for _, section := range requiredSections {
		content, ok := sectionContent(body, section)
		switch {
		case !ok:
			add("the %q section is missing", section)
		case content == "":
			add("the %q section is empty", section)
		}
	}

	problems = append(problems, s.referenceProblems(body)...)
	problems = append(problems, s.FolderProblems...)

	return problems
}

// referencePath is a reference the body declares: a backticked path under
// references/ that ends in .md. A phrase such as `references/<file>.md` is not a
// declaration, because it names no file.
var referencePath = regexp.MustCompile("`(references/[A-Za-z0-9._/-]+\\.md)`")

// referenceProblems applies the grammar every skill carries: what it returns, and
// -for a skill that carries depth- what the body names must exist, what the folder
// holds must be declared, and a router must gate every file.
func (s Skill) referenceProblems(body []string) []Problem {
	problems := []Problem{}
	add := func(format string, args ...any) {
		problems = append(problems, Problem{File: s.Path, Reason: fmt.Sprintf(format, args...)})
	}

	// The output contract belongs to every skill, not only to one that carries
	// depth: the agent has to know what it hands back whether or not a reference
	// taught it (0206).
	output, hasOutput := sectionContent(body, "Output")
	if !hasOutput || output == "" {
		add("every skill must say what it returns in %q: the agent has to know what to hand back", "Output")
	}

	named := referencedPaths(s.Body)
	folder := s.References
	if len(named) == 0 && len(folder) == 0 {
		return problems
	}

	for _, reference := range named {
		if !slices.Contains(folder, reference) {
			add("the reference %q does not exist: name the file the skill has, or write it", reference)
		}
	}

	for _, reference := range folder {
		if !strings.HasSuffix(reference, ".md") {
			add("the reference %q is not a .md: references/ holds the text an agent reads, nothing else", reference)
		}
	}

	references, hasReferences := sectionContent(body, "References")
	if !hasReferences {
		if len(folder) > 0 {
			add("a skill with references needs a %q section listing each file", "References")
		}
	} else {
		for _, reference := range folder {
			if !referenceListed(references, reference) {
				add("the reference %q is not a bullet of ## References: every file under references/ is one line of that list", reference)
			}
		}
	}

	if len(folder) > 1 {
		gates, hasGates := sectionContent(body, "Decision gates")
		switch {
		case !hasGates:
			add("a skill with %d references needs a %q table: one row per situation, the path in backticks", len(folder), "Decision gates")
		case gates == "":
			add("the %q section is empty: give each reference the situation that loads it", "Decision gates")
		default:
			for _, reference := range folder {
				if !gateRow(gates, reference) {
					add("the reference %q is not a row of ## Decision gates: a reference nobody routes is unreachable", reference)
				}
			}
		}
	}

	return problems
}

// referencedPaths returns the references the body names, in the order they
// appear and once each.
func referencedPaths(body string) []string {
	seen := map[string]bool{}
	paths := []string{}
	for _, match := range referencePath.FindAllStringSubmatch(body, -1) {
		reference := match[1]
		if seen[reference] {
			continue
		}
		seen[reference] = true
		paths = append(paths, reference)
	}
	return paths
}

// namesPath reports whether a section declares a reference by its exact path.
// referenceListed reports whether the inventory declares the path in a bullet:
// ## References is a list, one line per file, and a sentence that names the path
// declares nothing (0207).
func referenceListed(section, reference string) bool {
	needle := "`" + reference + "`"
	for _, line := range strings.Split(section, "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "- ") && !strings.HasPrefix(trimmed, "* ") {
			continue
		}
		if strings.Contains(trimmed, needle) {
			return true
		}
	}
	return false
}

// gateRow reports whether the table routes the path in a data row. The header
// names the columns and the separator names nothing, so neither routes (0207).
func gateRow(section, reference string) bool {
	needle := "`" + reference + "`"
	header := false
	for _, line := range strings.Split(section, "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "|") {
			continue
		}
		if separatorRow(trimmed) {
			continue
		}
		if !header {
			header = true
			continue
		}
		if strings.Contains(trimmed, needle) {
			return true
		}
	}
	return false
}

// separatorRow is the | --- | --- | line under a table's header.
func separatorRow(row string) bool {
	for _, r := range row {
		if r != '|' && r != '-' && r != ':' && r != ' ' && r != '\t' {
			return false
		}
	}
	return true
}

// Check validates a whole project: every file, unique names, and a registry that
// is exactly what --write would generate. hasRegistry is false when SKILLS.md
// does not exist, which is a violation with its own reason.
func Check(skills []Skill, registry string, hasRegistry bool) []Problem {
	problems := []Problem{}

	ordered := sortedByDir(skills)
	seen := make(map[string]Skill, len(ordered))
	for _, s := range ordered {
		problems = append(problems, s.Problems()...)
		if s.Name == "" {
			continue
		}
		if first, ok := seen[s.Name]; ok {
			problems = append(problems, Problem{
				File:   s.Path,
				Reason: fmt.Sprintf("the name %q is repeated: %s also uses it", s.Name, first.Path),
			})
			continue
		}
		seen[s.Name] = s
	}

	if !hasRegistry {
		problems = append(problems, Problem{
			File:   RegistryFile,
			Reason: "SKILLS.md is missing: run odachi skills --write to generate it",
		})
		return problems
	}
	if want := Registry(ordered); registry != want {
		problems = append(problems, Problem{
			File:   RegistryFile,
			Reason: "it is not what odachi skills --write would generate: do not edit it by hand, run odachi skills --write",
		})
	}

	return problems
}

// Registry renders SKILLS.md: the marker line, then the table sorted by name, and
// nothing else. Two runs over the same skills produce the same bytes.
func Registry(skills []Skill) string {
	ordered := append([]Skill(nil), skills...)
	sort.SliceStable(ordered, func(i, j int) bool {
		if ordered[i].Name != ordered[j].Name {
			return ordered[i].Name < ordered[j].Name
		}
		return ordered[i].Path < ordered[j].Path
	})

	var out strings.Builder
	out.WriteString(RegistryHeader + "\n")
	out.WriteString("| Skill | Trigger | Path |\n")
	out.WriteString("| --- | --- | --- |\n")
	for _, s := range ordered {
		name := s.Name
		if name == "" {
			name = s.Dir
		}
		path := s.Path
		if path == "" {
			path = "skills/" + s.Dir + "/SKILL.md"
		}
		fmt.Fprintf(&out, "| %s | %s | %s |\n", cell(name), cell(s.Trigger), cell(path))
	}
	return out.String()
}

// ValidSlug reports whether a slug may become a skill directory. `skill new`
// checks this before it writes anything.
func ValidSlug(slug string) bool {
	return namePattern.MatchString(slug)
}

// Template renders the SKILL.md `skill new` starts from: the four sections with
// a line to fill each, and a Trigger: the human completes. It is a valid skill
// as it stands, so `skills --check` stays green while the human writes.
func Template(name string) string {
	return "---\nname: " + name + "\ndescription: Trigger: (fill in when this skill is used)\n---\n\n" +
		"## When\n\n(say when this skill must be loaded)\n\n" +
		"## Rules\n\n(fill in the rules a senior would enforce)\n\n" +
		"## Output\n\n(what this skill hands back)\n\n" +
		"## Never\n\n(fill in what this skill never does)\n"
}

// splitFrontmatter cuts the --- block from the body. A file without both fences
// has no frontmatter at all; a truncated one is not half-accepted.
func splitFrontmatter(text string) (front, body string, ok bool) {
	text = strings.ReplaceAll(text, "\r\n", "\n")
	text = strings.TrimPrefix(text, "\ufeff")

	lines := strings.Split(text, "\n")
	if len(lines) == 0 || strings.TrimSpace(lines[0]) != "---" {
		return "", "", false
	}
	for i := 1; i < len(lines); i++ {
		if strings.TrimSpace(lines[i]) == "---" {
			return strings.Join(lines[1:i], "\n"), strings.Join(lines[i+1:], "\n"), true
		}
	}
	return "", "", false
}

// frontmatterValue reads one `key: value` line. Unknown keys are ignored: the
// format owns name and description, and a skill may keep its own notes.
func frontmatterValue(front, key string) string {
	for _, line := range strings.Split(front, "\n") {
		name, value, found := strings.Cut(line, ":")
		if !found || strings.TrimSpace(name) != key {
			continue
		}
		return unquote(strings.TrimSpace(value))
	}
	return ""
}

// unquote removes one pair of matching quotes, which YAML accepts and a human
// writing a trigger sentence sometimes uses.
func unquote(value string) string {
	if len(value) >= 2 {
		first, last := value[0], value[len(value)-1]
		if (first == '"' && last == '"') || (first == '\'' && last == '\'') {
			return value[1 : len(value)-1]
		}
	}
	return value
}

// bodyLines splits the body and drops the blank lines at both ends, so the
// count is about content, not about spacing around it.
func bodyLines(body string) []string {
	lines := strings.Split(body, "\n")
	for len(lines) > 0 && strings.TrimSpace(lines[0]) == "" {
		lines = lines[1:]
	}
	for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
		lines = lines[:len(lines)-1]
	}
	return lines
}

// sectionContent returns what follows a `## <heading>` line up to the next
// heading. ok is false when the section does not exist.
func sectionContent(lines []string, heading string) (content string, ok bool) {
	target := "## " + heading
	start := -1
	for i, line := range lines {
		if strings.TrimSpace(line) == target {
			start = i
			break
		}
	}
	if start < 0 {
		return "", false
	}

	var out strings.Builder
	for i := start + 1; i < len(lines); i++ {
		if strings.HasPrefix(strings.TrimSpace(lines[i]), "## ") {
			break
		}
		out.WriteString(lines[i])
		out.WriteString("\n")
	}
	return strings.TrimSpace(out.String()), true
}

// cell keeps one table cell on one line: a pipe inside a trigger would otherwise
// break the generated table.
func cell(value string) string {
	value = strings.ReplaceAll(value, "|", `\|`)
	value = strings.Join(strings.Fields(value), " ")
	return strings.TrimSpace(value)
}

// sortedByDir orders skills the way their directories are listed, which is also
// the order a human reads the messages in.
func sortedByDir(skills []Skill) []Skill {
	ordered := append([]Skill(nil), skills...)
	sort.SliceStable(ordered, func(i, j int) bool {
		if ordered[i].Dir != ordered[j].Dir {
			return ordered[i].Dir < ordered[j].Dir
		}
		return ordered[i].Path < ordered[j].Path
	})
	return ordered
}
